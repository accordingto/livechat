'use strict';
// Builds bingo-party-content.js from content/bingo-party-cards.final.json.
//   node scripts/bingo-party-build-content.cjs          write the module
//   node scripts/bingo-party-build-content.cjs --check  fail if it is stale or invalid
// The JSON is the delivered 60-card bilingual bank. Rules come from the
// engine and room settings; this build keeps only card text, never per-card
// timers, turn counts or legacy director twists.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'content', 'bingo-party-cards.final.json');
const target = path.join(root, 'bingo-party-content.js');
const TYPES = ['guess_person', 'song_relay', 'improv_scene', 'story_exchange', 'taboo_description'];

function pair(value, where) {
  const zh = value && typeof value['zh-TW'] === 'string' ? value['zh-TW'].trim() : '';
  const en = value && typeof value.en === 'string' ? value.en.trim() : '';
  if (!zh || !en) throw new Error(`missing zh/en text at ${where}`);
  return { zh, en };
}
function list(value, where) {
  const zh = Array.isArray(value?.['zh-TW']) ? value['zh-TW'].map(s => String(s).trim()).filter(Boolean) : [];
  const en = Array.isArray(value?.en) ? value.en.map(s => String(s).trim()).filter(Boolean) : [];
  if (zh.length !== 2 || en.length !== 2) throw new Error(`forbidden words must be 2 per language at ${where}`);
  return { zh, en };
}
function convert(raw) {
  if (raw.gameId !== 'bingo-party' || raw.schemaVersion !== 2) throw new Error('unexpected card bank');
  const ids = new Set();
  const cards = raw.cards.map(card => {
    if (!TYPES.includes(card.type)) throw new Error('unknown type ' + card.type);
    if (ids.has(card.id)) throw new Error('duplicate id ' + card.id);
    ids.add(card.id);
    for (const legacy of ['twists', 'twistAt', 'timedTwist', 'turnsPerTeam', 'secondsPerTurn', 'seconds', 'rounds'])
      if (Object.prototype.hasOwnProperty.call(card, legacy)) throw new Error(`legacy field ${legacy} in ${card.id}`);
    const out = { id: card.id, type: card.type, title: pair(card.title, card.id + '.title'), prompt: pair(card.prompt, card.id + '.prompt') };
    if (card.type === 'guess_person') {
      if (!Array.isArray(card.options) || card.options.length !== 3) throw new Error('guess needs 3 options ' + card.id);
      out.options = card.options.map((o, i) => ({ id: String(o.id || 'abc'[i]), text: pair(o.text, card.id + '.option') }));
      out.followUp = pair(card.followUp, card.id + '.followUp');
    } else if (card.type === 'song_relay') {
      out.rule = pair(card.validResponseRule, card.id + '.rule');
    } else if (card.type === 'improv_scene') {
      if (!Array.isArray(card.roles) || card.roles.length !== 2) throw new Error('improv needs 2 roles ' + card.id);
      out.roles = card.roles.map(r => pair(r, card.id + '.role'));
    } else if (card.type === 'story_exchange') {
      out.followUp = pair(card.suggestedFollowUp, card.id + '.followUp');
      out.safety = pair(card.safetyNote, card.id + '.safety');
    } else if (card.type === 'taboo_description') {
      if (!Array.isArray(card.targets) || card.targets.length !== 4) throw new Error('taboo needs 4 targets ' + card.id);
      out.targets = card.targets.map(t => ({ id: String(t.id), answer: pair(t.answer, card.id + '.answer'), forbidden: list(t.forbidden, card.id + '.forbidden') }));
    }
    return out;
  });
  for (const type of TYPES) {
    const n = cards.filter(c => c.type === type).length;
    if (n < 12) throw new Error(`${type} has ${n} cards, need at least 12`);
  }
  const d = raw.rulesDefaults || {};
  if (d.songRelay?.turnsPerTeam !== 4) throw new Error('song relay default must stay 4 turns per team');
  return { deckVersion: raw.deckVersion, rulesVersion: raw.rulesVersion, cards };
}
function render(bank) {
  return `/* bingo-party-content.js — GENERATED by scripts/bingo-party-build-content.cjs
 * from content/bingo-party-cards.final.json (${bank.deckVersion}). Do not edit by hand.
 * 60 bilingual starter cards, 12 per challenge type. Card text only: rules,
 * timers and turn counts live in bingo-party-engine.js and room settings.
 * The trusted authority (host page / host card) loads this file; ordinary
 * player cards do not, and projections never carry unrevealed answers. */
var BINGO_PARTY_CONTENT = ${JSON.stringify(bank, null, 1)};
if (typeof module !== 'undefined' && module.exports) module.exports = BINGO_PARTY_CONTENT;
`;
}
const bank = convert(JSON.parse(fs.readFileSync(source, 'utf8')));
const text = render(bank);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) { console.error('bingo-party-content.js is stale; run node scripts/bingo-party-build-content.cjs'); process.exit(1); }
  console.log(`bingo-party-content.js OK: ${bank.cards.length} cards`);
} else {
  fs.writeFileSync(target, text);
  console.log(`wrote bingo-party-content.js: ${bank.cards.length} cards`);
}
