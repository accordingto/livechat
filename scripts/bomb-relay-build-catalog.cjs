#!/usr/bin/env node
/* Build the existing classic browser/CJS deck. Edit the JSON sources only.
 * node scripts/bomb-relay-build-catalog.cjs [--check]
 */
'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
const SOURCE = 'content/bomb-relay-prompts.json';
const LEGACY_SOURCE = 'content/bomb-relay-legacy-scenes.json';
const OUTPUT = 'bomb-relay-deck.js';
const MANIFEST = 'content/bomb-relay-catalog-manifest.json';
const PATCH_SOURCE = 'content/bomb-relay-editorial-v3-patch.json';
const editorial = require('./bomb-relay-apply-editorial-patch.cjs');
const patch = require('../content/bomb-relay-editorial-v3-patch.json');
const FIELDS = ['id', 'pack', 'family', 'en', 'zhHant'];
const normalizedText = value => value.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, '').trim();
const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
const canonical = prompt => Object.fromEntries(FIELDS.map(field => [field, prompt[field]]));

function validateCatalog(catalog, legacy = []) {
  if (!Array.isArray(catalog) || !catalog.length) throw new Error('Prompt source must be a non-empty array.');
  if (!Array.isArray(legacy)) throw new Error('Legacy lookup source must be an array.');
  const ids = new Set(), english = new Set(), chinese = new Set();
  for (const prompt of catalog) {
    if (!prompt || typeof prompt !== 'object') throw new Error('Every prompt must be an object.');
    for (const field of FIELDS) {
      if (typeof prompt[field] !== 'string' || !prompt[field].trim() || prompt[field] !== prompt[field].trim()) throw new Error(`Invalid prompt ${field}: ${prompt.id || '(missing id)'}`);
    }
    if (!['everyday', 'playful'].includes(prompt.pack)) throw new Error(`Invalid prompt pack: ${prompt.id}`);
    if (ids.has(prompt.id)) throw new Error(`Duplicate prompt ID: ${prompt.id}`);
    ids.add(prompt.id);
    for (const [text, seen, label] of [[prompt.en, english, 'English'], [prompt.zhHant, chinese, 'Chinese']]) {
      const value = normalizedText(text);
      if (seen.has(value)) throw new Error(`Duplicate normalized ${label}: ${prompt.id}`);
      seen.add(value);
    }
  }
  for (const card of legacy) {
    if (!card || ['id', 'category', 'emoji', 'en', 'zh', 'art'].some(field => typeof card[field] !== 'string' || !card[field].trim())) throw new Error('Invalid legacy lookup card.');
    if (ids.has(card.id)) throw new Error(`Duplicate live/legacy ID: ${card.id}`);
    ids.add(card.id);
  }
}
const jsData = value => JSON.stringify(value, null, 2).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

function previousPrompts(catalog) {
  const byId = new Map(catalog.map(prompt => [prompt.id, prompt]));
  return patch.changes.filter(change => {
    const current = byId.get(change.id), marker = current?.[editorial.MARKER];
    return change.action === 'rewrite' && marker?.patchId === patch.patchId
      && marker.action === 'rewrite' && editorial.sameContent(current, change.after);
  }).map(change => change.before);
}
function renderDeck(catalog, legacy) {
  validateCatalog(catalog, legacy);
  const artVersion = legacy[0]?.art.match(/[?&]v=([^&]+)/)?.[1] || 'art-1';
  return `/* GENERATED by scripts/bomb-relay-build-catalog.cjs. DO NOT EDIT.
 * Prompt source: ${SOURCE} (one editable bilingual bank, including disabled IDs).
 * Previous wording is generated from the read-only ${PATCH_SOURCE} migration.
 * Legacy lookup-only source: ${LEGACY_SOURCE}; never in a new prompt pool.
 * Keep stable IDs: room promptHistory survives this content expansion.
 */
var BOMB_RELAY_DECK = (() => {
  'use strict';
  const ART_VERSION = ${JSON.stringify(artVersion)};
  const categories = Object.freeze(['mixed', 'everyday', 'playful']);
  const prompts = ${jsData(catalog)};
  const items = Object.freeze(prompts.map(prompt => Object.freeze(Object.assign({}, prompt, {
    category: prompt.pack, zh: prompt.zhHant, emoji: '💣',
  }))));
  const isEligible = prompt => prompt.disabled !== true && prompt.enabled !== false;
  const activeItems = Object.freeze(items.filter(isEligible));
  const legacyItems = Object.freeze(${jsData(legacy)}.map(Object.freeze));
  const byId = new Map([...legacyItems, ...items].map(card => [card.id, card]));
  const previousItems = ${jsData(previousPrompts(catalog))};
  const previousById = new Map(previousItems.map(prompt => [prompt.id, Object.freeze(Object.assign({}, prompt, {
    category: prompt.pack, zh: prompt.zhHant, emoji: '💣',
  }))]));
  return Object.freeze({
    ART_VERSION, categories, items, legacyItems, isEligible,
    get: id => byId.get(id) || null,
    // Migration-only: protect a pre-update bomb's wording, not new draws.
    getPrevious: id => previousById.get(id) || byId.get(id) || null,
    pool: mode => mode === 'mixed' ? activeItems : categories.includes(mode) ? activeItems.filter(prompt => prompt.pack === mode) : [],
  });
})();
if (typeof module !== 'undefined' && module.exports) module.exports = BOMB_RELAY_DECK;
`;
}
function makeManifest(catalog, legacy) {
  const counts = field => Object.fromEntries([...new Set(catalog.map(prompt => prompt[field]))].sort().map(value => [value, catalog.filter(prompt => prompt[field] === value).length]));
  const original = catalog.filter(prompt => /^tb-(everyday|playful)-\d{3}$/.test(prompt.id)
    && Number(prompt.id.split('-').at(-1)) >= 1 && Number(prompt.id.split('-').at(-1)) <= 60);
  return {
    generatedBy: 'scripts/bomb-relay-build-catalog.cjs', release: 'talk-bomb-content-3.0',
    source: SOURCE, total: catalog.length, packs: counts('pack'), families: counts('family'),
    activeTotal: catalog.filter(editorial.isEligible).length,
    activePacks: Object.fromEntries(['everyday', 'playful'].map(pack => [pack, catalog.filter(prompt => prompt.pack === pack && editorial.isEligible(prompt)).length])),
    disabledTotal: catalog.filter(prompt => !editorial.isEligible(prompt)).length,
    disabledIds: catalog.filter(prompt => !editorial.isEligible(prompt)).map(prompt => prompt.id),
    editorialPatch: PATCH_SOURCE, previousWordingCount: previousPrompts(catalog).length,
    retainedFromV1: original.length, originalDataSha256: hash(original.map(canonical)),
    catalogDataSha256: hash(catalog), legacyLookupOnly: legacy.length, legacyDataSha256: hash(legacy),
  };
}
function build({ check = false } = {}) {
  const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
  const legacy = JSON.parse(fs.readFileSync(path.join(ROOT, LEGACY_SOURCE), 'utf8'));
  const deck = renderDeck(catalog, legacy), manifest = makeManifest(catalog, legacy);
  for (const [file, text] of [[OUTPUT, deck], [MANIFEST, JSON.stringify(manifest, null, 2) + '\n']]) {
    const absolute = path.join(ROOT, file);
    if (check) {
      if (!fs.existsSync(absolute) || fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n') !== text) throw new Error(`Stale generated ${file}; run node scripts/bomb-relay-build-catalog.cjs`);
    } else fs.writeFileSync(absolute, text);
  }
  return manifest;
}
if (require.main === module) {
  try {
    const manifest = build({ check: process.argv.includes('--check') });
    console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${manifest.activeTotal} active / ${manifest.total} retained prompts: Everyday ${manifest.activePacks.everyday}, Playful ${manifest.activePacks.playful}; ${manifest.disabledTotal} deferred and ${manifest.legacyLookupOnly} legacy cards are lookup-only.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { build, renderDeck, validateCatalog, makeManifest, canonical, previousPrompts };
